create extension if not exists pgcrypto;

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'Colaborador',
  role text not null default 'viewer' check (role in ('admin','editor','viewer')),
  is_active boolean not null default false,
  created_at timestamptz not null default now()
);

create or replace function public.nucleo_new_user()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles (id, display_name)
  values (new.id, coalesce(nullif(split_part(new.email,'@',1),''),'Colaborador'))
  on conflict (id) do nothing;
  return new;
end;
$$;
create trigger nucleo_new_auth_user after insert on auth.users
for each row execute function public.nucleo_new_user();

create or replace function public.nucleo_member()
returns boolean language sql stable security definer set search_path = '' as $$
  select exists(select 1 from public.profiles
                where id = (select auth.uid()) and is_active = true);
$$;
create or replace function public.nucleo_editor()
returns boolean language sql stable security definer set search_path = '' as $$
  select exists(select 1 from public.profiles
                where id = (select auth.uid()) and is_active = true
                  and role in ('admin','editor'));
$$;
create or replace function public.nucleo_admin()
returns boolean language sql stable security definer set search_path = '' as $$
  select exists(select 1 from public.profiles
                where id = (select auth.uid()) and is_active = true and role = 'admin');
$$;
revoke all on function public.nucleo_member() from public;
revoke all on function public.nucleo_editor() from public;
revoke all on function public.nucleo_admin() from public;
grant execute on function public.nucleo_member(), public.nucleo_editor(), public.nucleo_admin() to authenticated;

create table public.tasks (
  id uuid primary key default gen_random_uuid(),
  number bigint generated by default as identity unique,
  title varchar(160) not null check (length(trim(title)) >= 2),
  description text not null default '',
  stage text not null default 'Backlog' check (stage in ('Backlog','Em análise','Em andamento','Em validação','Concluído')),
  priority text not null default 'Média' check (priority in ('Baixa','Média','Alta','Urgente')),
  due_date date,
  responsible varchar(160) not null default '',
  organization varchar(160) not null default '',
  neighborhood varchar(150) not null default '',
  city varchar(150) not null default 'São José do Rio Preto',
  street varchar(200) not null default '',
  street_number varchar(30) not null default '',
  postal_code varchar(9) not null default '',
  latitude double precision check (latitude between -90 and 90),
  longitude double precision check (longitude between -180 and 180),
  created_by uuid references auth.users(id),
  updated_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);
create index idx_tasks_stage on public.tasks(stage);
create index idx_tasks_due on public.tasks(due_date) where due_date is not null;
create index idx_tasks_neighborhood on public.tasks(lower(neighborhood));

create table public.checklist_items (
  id uuid primary key default gen_random_uuid(),
  task_id uuid not null references public.tasks(id) on delete cascade,
  title varchar(240) not null check (length(trim(title)) >= 2),
  is_done boolean not null default false,
  position integer not null default 0,
  created_at timestamptz not null default now()
);
create index idx_checklist_task on public.checklist_items(task_id, position);

create table public.task_comments (
  id uuid primary key default gen_random_uuid(),
  task_id uuid not null references public.tasks(id) on delete cascade,
  body text not null check (length(trim(body)) between 1 and 3000),
  author_id uuid not null references public.profiles(id),
  created_at timestamptz not null default now()
);
create index idx_comments_task on public.task_comments(task_id, created_at desc);

create table public.task_people (
  id uuid primary key default gen_random_uuid(),
  task_id uuid not null references public.tasks(id) on delete cascade,
  name varchar(150) not null check (length(trim(name)) >= 2),
  created_at timestamptz not null default now(),
  unique (task_id, name)
);
create index idx_people_task on public.task_people(task_id);

-- Metadados somente, nenhum arquivo binário armazenado no Supabase.
create table public.task_attachments (
  id uuid primary key default gen_random_uuid(),
  task_id uuid not null references public.tasks(id) on delete cascade,
  drive_file_id text not null unique,
  file_name varchar(220) not null,
  mime_type varchar(90) not null check (mime_type in ('image/jpeg','image/png','image/webp','application/pdf')),
  byte_size bigint not null check (byte_size between 1 and 15728640),
  uploaded_by uuid not null references public.profiles(id),
  created_at timestamptz not null default now()
);
create index idx_attachments_task on public.task_attachments(task_id, created_at desc);

create table public.task_activity (
  id uuid primary key default gen_random_uuid(),
  task_id uuid not null references public.tasks(id) on delete cascade,
  actor_id uuid references auth.users(id),
  event text not null,
  details text not null default '',
  created_at timestamptz not null default now()
);
create index idx_activity_task on public.task_activity(task_id, created_at desc);

create function public.nucleo_update_timestamp()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.updated_at = now();
  return new;
end;
$$;
create trigger tasks_set_updated_at before update on public.tasks
for each row execute function public.nucleo_update_timestamp();

create function public.nucleo_stage_history()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if old.stage is distinct from new.stage then
    insert into public.task_activity(task_id, actor_id, event, details)
    values(new.id, (select auth.uid()), 'mudanca_etapa', old.stage || ' → ' || new.stage);
  end if;
  return new;
end;
$$;
create trigger tasks_stage_history after update of stage on public.tasks
for each row execute function public.nucleo_stage_history();

-- ÚLTIMO ITEM CONCLUÍDO: avança EXATAMENTE uma coluna.
-- Não avança checklists vazios, nem ultrapassa 'Concluído'.
-- Reabrir um item não regride o cartão automaticamente.
create function public.nucleo_checklist_auto_advance()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if old.is_done = false and new.is_done = true
     and exists(select 1 from public.checklist_items where task_id = new.task_id)
     and not exists(select 1 from public.checklist_items
                    where task_id = new.task_id and is_done = false) then
    update public.tasks
      set stage = case stage
        when 'Backlog' then 'Em análise'
        when 'Em análise' then 'Em andamento'
        when 'Em andamento' then 'Em validação'
        when 'Em validação' then 'Concluído'
        else stage end
      where id = new.task_id and stage <> 'Concluído';
  end if;
  return new;
end;
$$;
create trigger checklist_auto_advance after update of is_done on public.checklist_items
for each row execute function public.nucleo_checklist_auto_advance();

