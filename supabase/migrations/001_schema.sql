create policy profiles_read on public.profiles for select to authenticated
using (id = (select auth.uid()) or (select public.nucleo_member()));
create policy profiles_admin_edit on public.profiles for update to authenticated
using ((select public.nucleo_admin())) with check ((select public.nucleo_admin()));

create policy tasks_read on public.tasks for select to authenticated
using ((select public.nucleo_member()));
create policy tasks_insert on public.tasks for insert to authenticated
with check ((select public.nucleo_editor()) and created_by = (select auth.uid()));
create policy tasks_edit on public.tasks for update to authenticated
using ((select public.nucleo_editor())) with check ((select public.nucleo_editor()));
create policy tasks_delete on public.tasks for delete to authenticated
using ((select public.nucleo_admin()));

create policy checklist_read on public.checklist_items for select to authenticated
using ((select public.nucleo_member()));
create policy checklist_insert on public.checklist_items for insert to authenticated
with check ((select public.nucleo_editor()));
create policy checklist_update on public.checklist_items for update to authenticated
using ((select public.nucleo_editor())) with check ((select public.nucleo_editor()));
create policy checklist_delete on public.checklist_items for delete to authenticated
using ((select public.nucleo_editor()));

create policy people_read on public.task_people for select to authenticated
using ((select public.nucleo_member()));
create policy people_insert on public.task_people for insert to authenticated
with check ((select public.nucleo_editor()));
create policy people_delete on public.task_people for delete to authenticated
using ((select public.nucleo_editor()));

create policy comments_read on public.task_comments for select to authenticated
using ((select public.nucleo_member()));
